#!/usr/bin/env python3
"""
build_web_ui.py
----------------
Generates web_ui.h -- a PROGMEM C header containing the ESP32's on-device web
control panel (HTML/CSS/JS, all inline, one file) and a static HTML rendering
of PROTOCOL.md for the on-device "Docs" tab. Same pattern as
coolledx_fallback.h (Python generates it, arduino-cli compiles it straight
into flash) -- no SD card dependency, no new upload mechanism, works even on
a board with no SD card wired up at all.

Why PROTOCOL.md gets converted to static HTML here rather than shipped as
raw markdown + a JS renderer: the ESP32's WiFi AP has no internet access, so
any markdown-parser library normally loaded from a CDN wouldn't load. This
avoids that entirely -- Python renders it once at bake time, plain HTML ships
in flash, zero JS dependencies. Images referenced in PROTOCOL.md are dropped
(a caption note is substituted) since embedding the actual JPEGs would add
close to a megabyte to flash -- see docs_images/ or the repo's PROTOCOL.md
directly for the photos.

Raw-send examples (for the Raw Send playground tab) are generated by calling
the real, hardware-verified *_bytes()/*_command_bytes() functions in
bake_messages_coolledux.py directly -- never hand-copied hex -- so the
examples can't drift out of sync with the actual protocol implementation.

Run this after bake_messages_coolledux.py (or anytime PROTOCOL.md or the
example set changes) and copy the resulting web_ui.h into the sketch folder,
same as coolledx_fallback.h.
"""

import html
import re
import base64

import bake_messages_coolledux as bmc

PROTOCOL_MD_PATH = "PROTOCOL.md"
OUTPUT_HEADER = "web_ui.h"


# ---------------------------------------------------------------------------
# Minimal markdown -> HTML converter. No external dependencies (keeps this
# script's own REQUIRES as small as bake_messages_coolledux.py's), and only
# needs to handle the subset of markdown PROTOCOL.md actually uses: headers,
# fenced code blocks, tables, bold/inline-code/links, hr, images (dropped),
# and a couple of raw embedded HTML blocks (passed through as-is).
# ---------------------------------------------------------------------------

def _inline(text: str) -> str:
    text = html.escape(text, quote=False)
    text = re.sub(r"`([^`]+)`", r"<code>\1</code>", text)
    text = re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", text)
    text = re.sub(r"!\[([^\]]*)\]\(([^)]+)\)", r"<p><i>[photo: \1]</i></p>", text)
    text = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", r'<a href="\2">\1</a>', text)
    return text


def markdown_to_html(md: str) -> str:
    lines = md.split("\n")
    out = []
    i = 0
    in_code = False
    code_lines = []
    in_table = False
    table_rows = []
    paragraph = []
    in_list = False

    def flush_paragraph():
        nonlocal in_list
        if in_list:
            out.append("</ul>")
            in_list = False
        if paragraph:
            out.append("<p>" + _inline(" ".join(paragraph)) + "</p>")
            paragraph.clear()

    def flush_table():
        nonlocal in_table
        if table_rows:
            out.append("<table class=\"md-table\">")
            header, *rest = table_rows
            out.append("<tr>" + "".join(f"<th>{_inline(c)}</th>" for c in header) + "</tr>")
            for row in rest:
                out.append("<tr>" + "".join(f"<td>{_inline(c)}</td>" for c in row) + "</tr>")
            out.append("</table>")
        table_rows.clear()
        in_table = False

    while i < len(lines):
        line = lines[i]
        stripped = line.strip()

        if stripped.startswith("```"):
            if not in_code:
                flush_paragraph()
                in_code = True
                code_lines = []
            else:
                out.append("<pre><code>" + html.escape("\n".join(code_lines)) + "</code></pre>")
                in_code = False
            i += 1
            continue
        if in_code:
            code_lines.append(line)
            i += 1
            continue

        if stripped.startswith("<"):
            # Raw embedded HTML block (the color-cycle side-by-side <table>) --
            # drop <img> tags (no image data in flash), pass the rest through.
            flush_paragraph()
            if "<img" in stripped:
                i += 1
                continue
            out.append(line)
            i += 1
            continue

        if stripped.startswith("|"):
            flush_paragraph()
            in_table = True
            if set(stripped.replace("|", "").strip()) <= set("-: "):
                i += 1
                continue
            cells = [c.strip() for c in stripped.strip("|").split("|")]
            table_rows.append(cells)
            i += 1
            continue
        elif in_table:
            flush_table()

        if stripped == "---":
            flush_paragraph()
            out.append("<hr>")
            i += 1
            continue

        m = re.match(r"^(#{1,4})\s+(.*)$", stripped)
        if m:
            flush_paragraph()
            level = len(m.group(1))
            out.append(f"<h{level}>{_inline(m.group(2))}</h{level}>")
            i += 1
            continue

        if stripped == "":
            flush_paragraph()
            i += 1
            continue

        m = re.match(r"^-\s+(.*)$", stripped)
        if m:
            if paragraph:
                flush_paragraph()
            if not in_list:
                out.append("<ul>")
                in_list = True
            out.append(f"<li>{_inline(m.group(1))}")
            i += 1
            continue

        if in_list:
            # Soft-wrapped continuation line of the current bullet (markdown
            # source wraps at ~80 cols without a blank line between); append
            # to the open <li> rather than starting a new paragraph.
            out[-1] = out[-1] + " " + _inline(stripped)
            i += 1
            continue

        paragraph.append(stripped)
        i += 1

    flush_paragraph()
    flush_table()
    return "\n".join(out)


def render_docs_html() -> str:
    md = open(PROTOCOL_MD_PATH, encoding="utf-8").read()
    body = markdown_to_html(md)
    return f"""<div class="docs">
<p class="docs-note"><i>Rendered from PROTOCOL.md at bake time. Photos are
dropped here (flash-only page) -- see the repo's docs_images/ folder or
PROTOCOL.md directly for those.</i></p>
{body}
</div>"""


# ---------------------------------------------------------------------------
# Raw-send examples for the playground tab. Every entry calls a REAL verified
# function from bake_messages_coolledux.py -- never hand-typed hex -- so
# these can't drift from the actual protocol implementation. Multi-packet
# examples (frame_border_bytes() etc.) are joined with "\n" so the firmware
# can loop through them with the same pacing as any other multi-chunk send.
# ---------------------------------------------------------------------------

def _pkts(packets) -> str:
    if isinstance(packets, (bytes, bytearray)):
        packets = [packets]
    return "\n".join(p.hex() for p in packets)


