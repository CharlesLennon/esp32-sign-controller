# ---------------------------------------------------------------------------
# Preview thumbnails for the Send-to-Display buttons -- like the official
# app's saved-program list, which shows a small preview of each button's
# actual content instead of just a text label. Rendered as inline SVG (no
# image library dependency, crisp at any size, tiny) directly from the same
# glyph-column data the real message is built from, so the preview can never
# drift out of sync with what actually gets sent -- it's the same source data,
# just rendered as a small dot-matrix picture instead of protocol bytes.
# ---------------------------------------------------------------------------

def _svg_pixel_grid(get_pixel_hex, width, height, cell=4):
    """Small SVG: black background, one small circle per lit pixel in its
    actual color -- a miniature mock-up of what the real 64x16 LED matrix
    would show. `cell` controls the SVG's internal coordinate scale, not
    display size (CSS controls the actual on-page size)."""
    svg_w, svg_h = width * cell, height * cell
    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {svg_w} {svg_h}">',
             f'<rect width="{svg_w}" height="{svg_h}" fill="#000"/>']
    r = cell * 0.42
    for x in range(width):
        for y in range(height):
            hexc = get_pixel_hex(x, y)
            if hexc:
                cx, cy = x * cell + cell / 2, y * cell + cell / 2
                parts.append(f'<circle cx="{cx:.1f}" cy="{cy:.1f}" r="{r:.1f}" fill="{hexc}"/>')
    parts.append("</svg>")
    return "".join(parts)


def _svg_data_uri(svg: str) -> str:
    b64 = base64.b64encode(svg.encode("utf-8")).decode("ascii")
    return f"data:image/svg+xml;base64,{b64}"


def _text_preview_pixel_fn(text, hex_color, small_font=False):
    columns = bmc.build_small_glyph_columns(text) if small_font else bmc.build_glyph_columns(text)

    def get_pixel(x, y):
        if x >= len(columns):
            return None
        bit = (columns[x] >> (15 - y)) & 1 if y < 16 else 0
        return hex_color if bit else None

    return get_pixel, len(columns)


def build_previews():
    """Returns {code: data-uri} for every real message/animation/game this
    script knows how to render a preview for. Codes with no preview here
    (e.g. a future SD-only custom message never seen by this script) just
    show no thumbnail in the web UI -- graceful, not an error."""
    previews = {}

    for code_name, text, color in bmc.MESSAGES:
        get_pixel, width = _text_preview_pixel_fn(text, color)
        width = max(width, 1)  # BLANK is 0-width text -- still show a tiny black square
        svg = _svg_pixel_grid(get_pixel, width, bmc.SIGN_HEIGHT)
        previews[code_name] = _svg_data_uri(svg)

    # Icon+scrolling-text messages (e.g. LPLATE): preview the icon plus the
    # first stretch of text (as if mid-scroll, arrived at the icon's edge) --
    # same real icon_pixel_fn used by the actual message, so it can't drift.
    for code_name, icon_pixel_fn, icon_width, text, text_color, _step, _delay, small_font in bmc.ICON_SCROLL_MESSAGES:
        text_get_pixel, _text_w = _text_preview_pixel_fn(text, text_color, small_font=small_font)

        def get_pixel(x, y, icon_pixel_fn=icon_pixel_fn, icon_width=icon_width, text_get_pixel=text_get_pixel):
            if x < icon_width:
                return icon_pixel_fn(x, y)
            return text_get_pixel(x - icon_width, y)

        svg = _svg_pixel_grid(get_pixel, bmc.SIGN_WIDTH, bmc.SIGN_HEIGHT)
        previews[code_name] = _svg_data_uri(svg)

    for code_name, text, color, *_rest in bmc.ANIMATIONS:
        # Preview the "arrived" (flush-left) frame -- representative of what
        # the message settles into and holds, not the fly-in motion itself.
        get_pixel, width = _text_preview_pixel_fn(text, color)
        svg = _svg_pixel_grid(get_pixel, width, bmc.SIGN_HEIGHT)
        previews[code_name] = _svg_data_uri(svg)

    # L-plate seamless messages (e.g. THANKS/SORRY): preview the held
    # "message" state (centered text, same real render_message_frame() the
    # actual animation uses), not the idle L-plate -- the text is what
    # distinguishes one button from another at a glance. Scrolling ones
    # (e.g. HONK) are too wide to render_message_frame() statically (that's
    # the whole reason they scroll) -- preview the first SIGN_WIDTH columns
    # of the real text instead, same idea as a scrolling ICON_SCROLL preview.
    for code_name, text, text_color, small_font, scroll, _style in bmc.L_PLATE_SEAMLESS_MESSAGES:
        if scroll:
            msg_pixel_fn, _w = _text_preview_pixel_fn(text, text_color, small_font=small_font)
        else:
            msg_pixel_fn = bmc.render_message_frame(text, text_color, small_font=small_font)
        svg = _svg_pixel_grid(msg_pixel_fn, bmc.SIGN_WIDTH, bmc.SIGN_HEIGHT)
        previews[code_name] = _svg_data_uri(svg)

    # HI: built as a one-off (waving hand, not in L_PLATE_SEAMLESS_MESSAGES) --
    # preview the neutral (tilt=0) wave frame, the real hold content.
    previews["HI"] = _svg_data_uri(_svg_pixel_grid(
        bmc.render_hi_wave_frame_fn(0), bmc.SIGN_WIDTH, bmc.SIGN_HEIGHT))

    # SNAKE: not literally frame-accurate (that's baked pixel data, not text/
    # glyph-derived like everything else here) -- a small hand-drawn
    # green-snake-and-red-apple icon instead, purely symbolic.
    def snake_icon(x, y):
        body = {(1, 8), (2, 8), (3, 8), (4, 7), (5, 6), (6, 6)}
        apple = {(10, 5)}
        if (x, y) in body:
            return "#00FF00"
        if (x, y) in apple:
            return "#FF0000"
        return None
    previews["SNAKE"] = _svg_data_uri(_svg_pixel_grid(snake_icon, bmc.SIGN_WIDTH, bmc.SIGN_HEIGHT))

    # LONGSNAKE: same idea, longer hand-drawn body to visually distinguish it
    # from the regular SNAKE icon at a glance.
    def longsnake_icon(x, y):
        body = {(1, 9), (2, 9), (3, 9), (4, 8), (5, 7), (6, 7), (7, 6), (8, 6),
                (9, 6), (10, 6), (11, 6), (12, 7), (13, 8)}
        apple = {(16, 4)}
        if (x, y) in body:
            return "#00FF00"
        if (x, y) in apple:
            return "#FF0000"
        return None
    previews["LONGSNAKE"] = _svg_data_uri(_svg_pixel_grid(longsnake_icon, bmc.SIGN_WIDTH, bmc.SIGN_HEIGHT))

    # BOUNCE: a small dotted trail suggesting back-and-forth motion, rather
    # than a single dot (which would look identical to "nothing lit").
    def bounce_icon(x, y, mid=bmc.SIGN_HEIGHT // 2):
        if y == mid and x in (4, 14, 24, 34, 44, 54):
            return "#00FF00"
        return None
    previews["BOUNCE"] = _svg_data_uri(_svg_pixel_grid(bounce_icon, bmc.SIGN_WIDTH, bmc.SIGN_HEIGHT))

    return previews


# ---------------------------------------------------------------------------
# Assemble the full page (template + rendered docs + examples JSON) and emit
# it as a PROGMEM C header, same pattern as coolledx_fallback.h: Python
# generates it, arduino-cli compiles it straight into flash, no separate
# upload step, works with no SD card at all.
# ---------------------------------------------------------------------------

def _c_string_literal(text: str) -> str:
    """Encode `text` as one or more adjacent C string literals (C
    concatenates these automatically) so no single line/literal gets
    unreasonably long. Escapes backslashes, quotes, and newlines."""
    escaped = (text.replace("\\", "\\\\")
                    .replace('"', '\\"')
                    .replace("\r", "")
                    .replace("\n", "\\n\n"))
    lines = escaped.split("\n")
    chunks = []
    buf = ""
    for line in lines:
        if len(buf) + len(line) > 400:
            chunks.append(buf)
            buf = ""
        buf += line
    if buf:
        chunks.append(buf)
    return "\n".join(f'  "{c}"' for c in chunks)


def build_index_html() -> str:
    template = open("web_ui_template.html", encoding="utf-8").read()
    docs_html = render_docs_html()
    examples = build_examples()
    previews = build_previews()
    import json
    examples_json = json.dumps(examples)
    previews_json = json.dumps(previews)
    page = (template.replace("__DOCS_HTML__", docs_html)
                     .replace("__EXAMPLES_JSON__", examples_json)
                     .replace("__PREVIEWS_JSON__", previews_json))
    return page


def write_web_ui_header(output_path: str = OUTPUT_HEADER):
    index_html = build_index_html()
    header = []
    header.append("// AUTO-GENERATED by build_web_ui.py -- do not hand-edit.")
    header.append("// Regenerate with: python build_web_ui.py")
    header.append("// Contains the ESP32's on-device web control panel (Control/Raw Send/Docs")
    header.append("// tabs) as one self-contained HTML page (inline CSS+JS, no external")
    header.append("// requests -- the WiFi AP has no internet access). Docs tab is a static")
    header.append("// HTML rendering of PROTOCOL.md baked in at generation time; Raw Send")
    header.append("// examples are real hex from bake_messages_coolledux.py's verified")
    header.append("// *_bytes() functions, never hand-typed.")
    header.append("#pragma once")
    header.append("")
    header.append(f"// {len(index_html)} bytes of HTML/CSS/JS")
    header.append("static const char INDEX_HTML[] PROGMEM =")
    header.append(_c_string_literal(index_html) + ";")
    header.append("")
    with open(output_path, "w", encoding="utf-8") as f:
        f.write("\n".join(header) + "\n")
    print(f"Wrote {output_path} ({len(index_html)} bytes of HTML embedded, "
          f"{sum(1 for _ in open(output_path))} lines total)")


if __name__ == "__main__":
    write_web_ui_header()
